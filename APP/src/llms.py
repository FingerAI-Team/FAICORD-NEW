from openai import OpenAI
import torch

class LLMModel():
    def __init__(self, config):
        self.config = config 

    def set_gpu(self, model):
        self.device = torch.device("cuda") if torch.cuda.is_available() else "cpu"    
        model.to(self.device)
    
    def set_generation_config(self, max_tokens=15000, temperature=0.05):
        self.gen_config = {
            "max_tokens": max_tokens,
            "temperature": temperature
        }

class LLMOpenAI(LLMModel):
    def __init__(self, config, api_key):
        super().__init__(config)
        self.client = OpenAI(api_key=api_key)

    def set_generation_config(self):
        self.gen_config = {
            "max_tokens": self.config['max_tokens'],
            "temperature": self.config['temperature']
        }

    def set_summary_guideline(self):
        '''
        STT 결과값을 보고, 회의록을 작성하기 위한 요약 템플릿입니다.  
        '''
        self.system_role = """
        당신은 회의 녹취록을 요약하여 구조화된 회의록 문서를 작성하는 AI 비서입니다. 사용자에게 도움이 될 수 있도록, 회의 내용을 안건별로 분류하고 논의된 핵심 사항과 결정사항, 향후 일정을 명확히 정리하세요. 출력은 마크다운 형식으로 작성합니다.
        녹취록 내 각 항목은 한 발언을 나타내며, "speaker"는 발언자 이름 (없으면 빈 문자열), "text"는 발언 내용입니다. 이 데이터를 분석하여 **내부 공유용 회의록**을 작성해 주세요:
        
        **요구사항:**
        - 회의에서 논의된 내용을 **주요 안건별로 분류 및 정리**합니다.
        + 각 안건 아래에 **발언자별 주요 의견**을 bullet 형태로 정리하되, 발언자는 주어진 `"speaker"` 값(SPEAKER_00 등)을 그대로 사용합니다.
        + 발언자의 실명 또는 직책은 표기하지 않습니다.
        - **결정된 사항**과 **향후 일정**(액션 아이템)이 언급된 경우 모두 식별하여 정리합니다.
        - **입력에 주어진 내용만** 사용하고, 주어진 내용에 없는 추측이나 창작을 하지 않습니다.
        - **회의 내용의 분량에 따라** 요약의 길이와 상세함을 조절합니다 (내용이 많으면 자세히, 적으면 간략히).

        **출력 형식:**
        다음의 마크다운 구조를 따라 작성하세요 (각 대괄호 부분을 실제 내용으로 채워 넣을 것):

        ## 안건
        1. [안건 또는 주제 1]
        2. [안건 또는 주제 2]
        ...

        ## 논의 사항
        ### 안건 1: [안건 1의 제목]
        - [발언자1 이름 또는 '참석자']: [해당 발언자의 핵심 의견 요약]
        - [발언자2 이름 또는 '참석자']: [다른 참여자의 주요 발언 요약]
        ... (필요한 만큼 추가)
        - 결정사항: [안건 1과 관련하여 결정된 사항이 있다면 명시]

        ### 안건 2: [안건 2의 제목]
        - [발언자]: [핵심 의견 요약]
        ...
        - 결정사항: [결정된 사항이 있으면 명시, 없으면 제외]

        ## 참고사항
        ### 향후일정
        - [향후 수행해야 할 작업 또는 일정 1]: [예정 일자 또는 기한]
        - [향후 수행해야 할 작업 또는 일정 2]: [예정 일자 또는 기한]
        ... (필요 시 추가)

        ### 결정사항
        1. [회의 전체적으로 나온 중요한 결정사항 1]
        2. [결정사항 2]
        ... (필요 시 추가)

        위 형식을 참고하여, 회의 내용을 **안건별**로 요약하고 **결정사항**과 **향후일정**까지 빠짐없이 정리해 주세요.
        """

        self.sub_role = """
            - 각 안건의 논의 사항은 발언자의 핵심 발언을 **요약하되**, 세부 설명, 구현 방식, 예시, 수치 등이 포함되도록 작성해 주세요.
            - 기술, 기능, 구조, 적용 방식 등은 **단순 언급이 아닌 설명 중심으로** 정리해 주세요.  
            - 동일 화자가 여러 주제를 언급한 경우, **항목별로 문단을 나눠 상세하게 정리**해 주세요.
            - 시연 관련 발언은 "**기능 설명 + 실제 시연 흐름 + 결과 또는 효과**" 순서로 서술해 주세요.  
            - 논의 중 등장한 **핵심 기술, 기능, 구조적 요소**는 안건 내에서 **별도 항목 또는 문단**으로 구분하여 설명해 주세요.  
            - 해당 요소에 대해 가능한 한 **적용 방식, 구성 조건, 수치 범위, 제약사항 및 실제 사례** 등을 포함해 주세요.
                ex) 사용자 정의 기능, 인식 정확도 보정 방식, 학습 방법론, 인프라 운영 구조 등            
            - 발언자 이름은 JSON의 "speaker" 필드 값 그대로 사용합니다 (예: SPEAKER_00, SPEAKER_01 등). 실명, 직책 등은 사용하지 않습니다.
            - 회의 발언 수가 많은 경우, 안건당 최소 5개 이상의 bullet 또는 문단을 유지해 주세요.
            - 요약은 단순한 축약이 아니라, **발언 흐름과 논리 구조를 재구성하여 명확하게 전달하는 것**을 목표로 합니다.
            - 기술적 설명, 실제 시연, 운영 구조, 적용 사례, 협업/테스트 계획 등 **성격이 다른 논의는 반드시 별도의 안건으로 구분**해 주세요.
            - 발언 내용이 반복되거나 유사한 경우, **중복된 문장은 생략하거나 하나로 통합하여 핵심만 정리**해 주세요.
            - 동일한 주제를 여러 번 반복한 경우, **"강조 발언"인지 여부를 판단해**, 실제 의미 변화가 없다면 **1회만 요약**해 주세요.
            - 반복된 표현으로 인해 **정보 밀도나 문서 품질이 떨어지지 않도록** 정리해 주세요.
            - 화자의 발언 중 **일정, 타이밍, 회의 시점과 관련된 표현(예: '다음 주', '이번 달 말', 'POC 끝나고 나서', '다음 회의 때 다시 보기로')**이 포함된 경우, 이를 반드시 "향후 일정" 섹션에 정리해 주세요.
                - 날짜가 명확하지 않더라도, **상대적 표현(다음 회의, 다음 논의, 시연 완료 후, 협업 논의 이후 등)**을 일정 항목으로 포함해 주세요.
                - 특히 “다음 회의가 언제인지”, “다음 논의가 예정되어 있는지”, “차기 POC 결과 공유 시점” 등은 **정확한 시점 없이도 향후 일정 항목에 반드시 포함**해야 합니다.
                - 다음 회의가 확정되지 않았더라도, “다음 회의 일정을 조율할 예정”, “다음 논의는 시연 이후로 예정” 등으로도 표현해 주세요.
            - **제품화 제안, 실사용 경험 공유, 경쟁력 차별화 요소에 대한 의견** 등 정형적이지 않은 내용도 **중요한 발언으로 간주하여 누락 없이 요약**해 주세요.
                ex) 실제 컨퍼런스 경험을 기반으로 한 불편 사례 제시, 경쟁사 제품과의 비교, 기능 조합 아이디어 등
            - 단순한 발언 나열 대신, **안건별로 기술 구조, 구현 흐름, 기대 효과를 중심으로 문단을 재구성**하여 작성해 주세요.
            - 시연 계획이나 POC 예정 사항도, **어떤 조건/환경/기대 성능 하에서 어떻게 진행되는지** 가능한 상세하게 정리해 주세요.
            - 동일 주제에 대해 여러 화자가 발언하더라도, 각 화자의 입장을 명확히 구분하여 작성해 주세요.
            - 어떤 내용도 화자를 바꾸거나 대표화하지 마세요. 예: SPEAKER_06이 말한 내용을 SPEAKER_00에게 합치지 마세요.
        """

    def set_prompt_template(self, query):
        self.meeting_log_prompt_template = """
        {query} 
        """
        return self.meeting_log_prompt_template.format(query=query)
        
    def get_response(self, query, role="너는 금융권에서 일하고 있는 조수로, 사용자 질문에 대해 간단 명료하게 답을 해주면 돼", sub_role="", model='gpt-4o'):
        try:
            sub_role = sub_role
            response = self.client.chat.completions.create(
                model=model,
                messages=[
                    {"role": "system", "content": role},
                    {"role": "system", "content": sub_role},
                    {"role": "user", "content": query},
                ],
                max_tokens=self.gen_config['max_tokens'],
                temperature=self.gen_config['temperature'],
            )
        except Exception as e:
            return f"Error: {str(e)}"
        return response.choices[0].message.content